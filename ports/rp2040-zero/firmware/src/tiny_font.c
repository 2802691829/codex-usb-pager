bool tiny_font_sample(char glyph, uint8_t x, uint8_t y) {
    size_t index;

    if (x >= TINY_FONT_WIDTH || y >= TINY_FONT_HEIGHT) {
        return false;
    }
    for (index = 0U; index < sizeof(glyphs) / sizeof(glyphs[0]); ++index) {
        if (glyphs[index].glyph == glyph) {
            return (glyphs[index].rows[y] &
                    (uint8_t)(1U << (TINY_FONT_WIDTH - 1U - x))) != 0U;
        }
    }
    return false;
}
